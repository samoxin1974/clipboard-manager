import Foundation
import AppKit
import Combine
import UniformTypeIdentifiers

struct SourceOption: Identifiable, Hashable {
    let bundleID: String
    let name: String

    var id: String { bundleID.isEmpty ? "__unknown__" : bundleID }
}

@MainActor
final class AppState: ObservableObject {
    let paths: AppPaths
    let database: ClipboardDatabase
    let imageStore: ImageStore
    let normalizer: ClipboardNormalizer
    let monitor: ClipboardMonitor
    let ocrService: OCRService
    let pasteController: PasteController
    let hotkeyController: HotkeyController
    let settings: SettingsStore

    @Published var items: [ClipItem] = []
    @Published var snippets: [Snippet] = []
    @Published var searchText = ""
    @Published var filter: HistoryFilter = .all
    @Published var sourceFilter: String?
    @Published var selectedItemID: String?
    @Published var selectedSnippetID: String?
    @Published var mode: PanelMode = .history
    @Published var toast: String?
    @Published var accessibilityTrusted: Bool
    @Published var focusSearchRequest = 0
    @Published var searchFieldFocused = false
    @Published var snippetTitleFocused = false
    @Published var saveSnippetRequest = 0
    @Published var copySnippetRequest = 0
    @Published var pasteSnippetRequest = 0
    @Published var isMonitoringPaused: Bool
    @Published var launchAtLoginStatus: String
    @Published var lastError: String?

    weak var panelController: HistoryPanelController?
    weak var settingsWindowController: SettingsWindowController?

    private(set) var previousApp: NSRunningApplication?
    private var lastGoodShortcut: GlobalShortcut
    private var isApplyingShortcut = false
    private var toastWorkItem: DispatchWorkItem?

    init(paths: AppPaths) throws {
        self.paths = paths
        database = try ClipboardDatabase(url: paths.databaseURL)
        imageStore = ImageStore(directory: paths.imageDirectory)
        normalizer = ClipboardNormalizer(imageStore: imageStore)
        pasteController = PasteController(imageStore: imageStore)
        ocrService = OCRService()
        settings = SettingsStore()
        monitor = ClipboardMonitor(normalizer: normalizer)
        hotkeyController = HotkeyController()
        accessibilityTrusted = AccessibilityPermission.isTrusted
        isMonitoringPaused = !settings.monitorEnabled
        launchAtLoginStatus = LaunchAtLoginManager.statusText
        lastGoodShortcut = settings.shortcut
        AppLog.write("settings: maxItems=\(settings.maxItems) retention=\(settings.retentionDays) ocr=\(settings.ocrEnabled) autoPaste=\(settings.pasteAutomatically) rich=\(settings.pasteRichText) concealed=\(settings.skipConcealed) generated=\(settings.skipAutoGenerated) monitor=\(settings.monitorEnabled)")

        monitor.onCapture = { [weak self] item in
            self?.handleCapture(item)
        }
        hotkeyController.onHotkey = { [weak self] in
            self?.panelController?.toggle()
        }
        settings.onShortcutChanged = { [weak self] shortcut in
            self?.applyShortcut(shortcut)
        }
        settings.onHistorySettingsChanged = { [weak self] in
            self?.applyHistorySettings()
        }
        settings.onMonitorSettingsChanged = { [weak self] in
            self?.applyMonitorSettings()
        }

        reloadItems(preserveSelection: false)
        reloadSnippets()
        applySettingsForLaunch()
    }

    func start() {
        monitor.configure(
            skipConcealed: settings.skipConcealed,
            skipAutoGenerated: settings.skipAutoGenerated
        )
        monitor.setPaused(!settings.monitorEnabled)
        monitor.start()
        trimHistory()
    }

    func shutdown() {
        monitor.stop()
        hotkeyController.unregister()
    }

    private func applySettingsForLaunch() {
        ocrService.isEnabled = settings.ocrEnabled
        monitor.configure(
            skipConcealed: settings.skipConcealed,
            skipAutoGenerated: settings.skipAutoGenerated
        )
        monitor.setPaused(!settings.monitorEnabled)
        do {
            try hotkeyController.register(settings.shortcut)
            lastGoodShortcut = settings.shortcut
        } catch {
            AppLog.write("hotkey registration failed: \(error.localizedDescription)")
            showToast(error.localizedDescription)
        }
        trimHistory()
    }

    var filteredItems: [ClipItem] {
        let query = searchText.trimmed.lowercased()
        return items.filter { item in
            guard filter.matches(item) else { return false }
            if let sourceFilter {
                let itemSource = item.sourceBundleID ?? ""
                if itemSource != sourceFilter { return false }
            }
            if query.isEmpty { return true }
            return item.searchText.contains(query)
        }
    }

    var filteredSnippets: [Snippet] {
        let query = searchText.trimmed.lowercased()
        guard !query.isEmpty else { return snippets }
        return snippets.filter {
            $0.title.lowercased().contains(query) || $0.body.lowercased().contains(query)
        }
    }

    var selectedItem: ClipItem? {
        guard let selectedItemID else { return nil }
        return items.first { $0.id == selectedItemID }
    }

    var selectedSnippet: Snippet? {
        guard let selectedSnippetID else { return nil }
        return snippets.first { $0.id == selectedSnippetID }
    }

    var sourceOptions: [SourceOption] {
        var seen = Set<String>()
        var result: [SourceOption] = []
        for item in items {
            let bundleID = item.sourceBundleID ?? ""
            guard seen.insert(bundleID).inserted else { continue }
            result.append(SourceOption(bundleID: bundleID, name: item.sourceName ?? "Unknown app"))
        }
        return result.sorted { $0.name.localizedCaseInsensitiveCompare($1.name) == .orderedAscending }
    }

    var pinnedCount: Int {
        items.filter(\.pinned).count
    }

    var dataFolderPath: String {
        paths.applicationSupportDirectory.path
    }

    var storageDescription: String {
        let dbSize = ByteCountFormatter.string(fromByteCount: database.databaseSize(), countStyle: .file)
        let imageBytes = imageStore.totalBytes()
        let imageSize = imageBytes == 0
            ? "0 KB"
            : ByteCountFormatter.string(fromByteCount: imageBytes, countStyle: .file)
        return "\(items.count) items · database \(dbSize) · images \(imageSize)"
    }

    func reloadItems(preserveSelection: Bool = true) {
        let oldSelection = selectedItemID
        do {
            items = try database.recent(limit: 5_000)
        } catch {
            AppLog.write("reload items failed: \(error.localizedDescription)")
            items = []
        }
        if preserveSelection, let oldSelection, items.contains(where: { $0.id == oldSelection }) {
            selectedItemID = oldSelection
        } else if let selectedItemID, !items.contains(where: { $0.id == selectedItemID }) {
            self.selectedItemID = filteredItems.first?.id
        } else if self.selectedItemID == nil {
            selectedItemID = filteredItems.first?.id
        }
    }

    func reloadSnippets(preserveSelection: Bool = true) {
        let oldSelection = selectedSnippetID
        do {
            snippets = try database.allSnippets()
        } catch {
            AppLog.write("reload snippets failed: \(error.localizedDescription)")
            snippets = []
        }
        if preserveSelection, let oldSelection, snippets.contains(where: { $0.id == oldSelection }) {
            selectedSnippetID = oldSelection
        } else if selectedSnippetID == nil || !snippets.contains(where: { $0.id == selectedSnippetID }) {
            selectedSnippetID = snippets.first?.id
        }
    }

    func handleCapture(_ incoming: ClipItem) {
        do {
            let result = try database.save(incoming)
            reloadItems(preserveSelection: true)
            if result.inserted || result.item.ocrText == nil,
               result.item.kind == .image,
               settings.ocrEnabled,
               let fileName = result.item.imageFileName {
                scheduleOCR(id: result.item.id, fileName: fileName)
            }
            let removed = try database.trim(
                maxItems: settings.maxItems,
                retentionDays: settings.retentionDays
            )
            if !removed.isEmpty {
                imageStore.delete(fileNames: removed)
                reloadItems(preserveSelection: true)
            }
        } catch {
            AppLog.write("save clipboard item failed: \(error.localizedDescription)")
        }
    }

    private func scheduleOCR(id: String, fileName: String) {
        let url = imageStore.fileURL(for: fileName)
        guard let data = try? Data(contentsOf: url) else {
            AppLog.write("ocr skipped: could not read \(fileName)")
            return
        }
        AppLog.write("ocr scheduled: \(id) bytes=\(data.count)")
        ocrService.recognize(imageData: data) { [weak self] text in
            AppLog.write("ocr completed: chars=\(text?.count ?? 0)")
            self?.applyOCR(id: id, text: text)
        }
    }

    private func applyOCR(id: String, text: String?) {
        guard let text, !text.isEmpty, let index = items.firstIndex(where: { $0.id == id }) else { return }
        let item = items[index]
        let search = SearchTextBuilder.withOCR(item, ocrText: text)
        do {
            try database.updateOCR(id: id, text: text, searchText: search)
            items[index].ocrText = text
            items[index].searchText = search
        } catch {
            AppLog.write("save ocr failed: \(error.localizedDescription)")
        }
    }

    private func trimHistory() {
        do {
            let removed = try database.trim(
                maxItems: settings.maxItems,
                retentionDays: settings.retentionDays
            )
            if !removed.isEmpty {
                imageStore.delete(fileNames: removed)
                reloadItems(preserveSelection: true)
            }
        } catch {
            AppLog.write("trim history failed: \(error.localizedDescription)")
        }
    }

    private func applyHistorySettings() {
        ocrService.isEnabled = settings.ocrEnabled
        trimHistory()
        reloadItems(preserveSelection: true)
    }

    private func applyMonitorSettings() {
        monitor.configure(
            skipConcealed: settings.skipConcealed,
            skipAutoGenerated: settings.skipAutoGenerated
        )
        monitor.setPaused(!settings.monitorEnabled)
        isMonitoringPaused = !settings.monitorEnabled
    }

    private func applyShortcut(_ shortcut: GlobalShortcut) {
        guard !isApplyingShortcut else { return }
        do {
            try hotkeyController.register(shortcut)
            lastGoodShortcut = shortcut
        } catch {
            isApplyingShortcut = true
            settings.shortcut = lastGoodShortcut
            try? hotkeyController.register(lastGoodShortcut)
            isApplyingShortcut = false
            showToast(error.localizedDescription)
        }
    }

    func toggleMonitoring() {
        settings.monitorEnabled.toggle()
    }

    func panelWillShow(mode: PanelMode) {
        let front = NSWorkspace.shared.frontmostApplication
        if front?.bundleIdentifier != Bundle.main.bundleIdentifier {
            previousApp = front
        }
        self.mode = mode
        reloadItems(preserveSelection: true)
        reloadSnippets(preserveSelection: true)
        refreshAccessibilityStatus()
        launchAtLoginStatus = LaunchAtLoginManager.statusText
        focusSearchRequest += 1
        if mode == .snippets {
            ensureSnippetSelectionVisible()
        } else {
            ensureSelectionVisible()
        }
    }

    func restorePreviousApp() {
        guard let previousApp, !previousApp.isTerminated else { return }
        guard previousApp.bundleIdentifier != Bundle.main.bundleIdentifier else { return }
        pasteController.activate(previousApp)
    }

    func refreshAccessibilityStatus() {
        accessibilityTrusted = AccessibilityPermission.isTrusted
        launchAtLoginStatus = LaunchAtLoginManager.statusText
    }

    func requestAccessibilityPermission() {
        AccessibilityPermission.requestPrompt()
        refreshAccessibilityStatus()
        if !accessibilityTrusted {
            AccessibilityPermission.openSystemSettings()
        }
    }

    func ensureSelectionVisible() {
        let visible = filteredItems
        if let selectedItemID, visible.contains(where: { $0.id == selectedItemID }) { return }
        selectedItemID = visible.first?.id
    }

    func ensureSnippetSelectionVisible() {
        let visible = filteredSnippets
        if let selectedSnippetID, visible.contains(where: { $0.id == selectedSnippetID }) { return }
        selectedSnippetID = visible.first?.id
    }

    func select(_ item: ClipItem) {
        selectedItemID = item.id
    }

    func selectSnippet(_ snippet: Snippet) {
        selectedSnippetID = snippet.id
    }

    func moveSelection(by delta: Int) {
        let visible = filteredItems
        guard !visible.isEmpty else { return }
        let currentIndex = visible.firstIndex { $0.id == selectedItemID } ?? 0
        let next = min(max(currentIndex + delta, 0), visible.count - 1)
        selectedItemID = visible[next].id
    }

    func moveSnippetSelection(by delta: Int) {
        let visible = filteredSnippets
        guard !visible.isEmpty else { return }
        let currentIndex = visible.firstIndex { $0.id == selectedSnippetID } ?? 0
        let next = min(max(currentIndex + delta, 0), visible.count - 1)
        selectedSnippetID = visible[next].id
    }

    func quickPaste(index: Int) {
        let visible = filteredItems
        guard index >= 0, index < visible.count else { return }
        selectedItemID = visible[index].id
        pasteSelected()
    }

    func quickPasteSnippet(index: Int) {
        let visible = filteredSnippets
        guard index >= 0, index < visible.count else { return }
        selectedSnippetID = visible[index].id
        pasteSelectedSnippet()
    }

    func togglePinSelected() {
        guard let item = selectedItem else { return }
        do {
            try database.setPinned(!item.pinned, id: item.id)
            reloadItems(preserveSelection: true)
            showToast(item.pinned ? "Unpinned" : "Pinned")
        } catch {
            showAlert(title: "Could Not Update Pin", message: error.localizedDescription)
        }
    }

    func togglePin(_ item: ClipItem) {
        selectedItemID = item.id
        togglePinSelected()
    }

    func deleteSelected() {
        guard let item = selectedItem else { return }
        delete(item)
    }

    func delete(_ item: ClipItem) {
        do {
            let fileNames = try database.delete(id: item.id)
            imageStore.delete(fileNames: fileNames)
            let index = filteredItems.firstIndex { $0.id == item.id } ?? 0
            reloadItems(preserveSelection: false)
            let visible = filteredItems
            if !visible.isEmpty {
                selectedItemID = visible[min(index, visible.count - 1)].id
            }
            showToast("Item deleted")
        } catch {
            showAlert(title: "Could Not Delete Item", message: error.localizedDescription)
        }
    }

    func clearHistory(keepPinned: Bool) {
        do {
            let fileNames = try database.clear(keepPinned: keepPinned)
            imageStore.delete(fileNames: fileNames)
            reloadItems(preserveSelection: false)
            showToast(keepPinned ? "History cleared, pinned items kept" : "History cleared")
        } catch {
            showAlert(title: "Could Not Clear History", message: error.localizedDescription)
        }
    }

    func copySelected(asPlainText: Bool = false) {
        guard let item = selectedItem else { return }
        copy(item, asPlainText: asPlainText)
    }

    func copy(_ item: ClipItem, asPlainText: Bool = false) {
        let variant: PasteVariant = asPlainText ? .plainText : .normal
        let forcePlain = !settings.pasteRichText
        if pasteController.write(item: item, variant: variant, plainTextOverride: forcePlain) {
            monitor.noteOwnPasteboardWrite()
            showToast("Copied to clipboard")
        } else {
            showToast("Could not copy this item")
        }
    }

    func pasteSelected(variant: PasteVariant = .normal) {
        if mode == .snippets {
            pasteSelectedSnippet()
            return
        }
        guard let item = selectedItem else { return }
        paste(item, variant: variant)
    }

    func paste(_ item: ClipItem, variant: PasteVariant = .normal, autoPaste: Bool = true) {
        if variant.isTransform {
            guard item.plainText != nil else { return }
            guard let transformed = variant.apply(to: item.plainText ?? "") else {
                showToast("That transform could not be applied")
                return
            }
            let newItem = ClipItem(
                createdAt: Date(),
                kind: .text,
                plainText: transformed,
                sourceBundleID: Bundle.main.bundleIdentifier,
                sourceName: "Clipboard Manager",
                contentHash: StableHash.string("text|\(transformed)"),
                byteSize: transformed.utf8.count,
                searchText: SearchTextBuilder.build(
                    kind: .text,
                    plainText: transformed,
                    htmlText: nil,
                    filePaths: [],
                    colorHex: nil,
                    sourceName: nil,
                    ocrText: nil
                )
            )
            if let result = try? database.save(newItem) {
                reloadItems(preserveSelection: true)
                selectedItemID = result.item.id
            }
            pasteController.write(text: transformed)
            monitor.noteOwnPasteboardWrite()
            if autoPaste {
                finalizePaste()
            } else {
                showToast("Transformed copy on clipboard")
            }
            return
        }

        let forcePlain = !settings.pasteRichText || variant == .plainText
        guard pasteController.write(item: item, variant: variant, plainTextOverride: forcePlain) else {
            showToast("Could not prepare this item for pasting")
            return
        }
        monitor.noteOwnPasteboardWrite()
        if autoPaste {
            finalizePaste()
        } else {
            showToast("Copied to clipboard")
        }
    }

    private func finalizePaste() {
        if !settings.pasteAutomatically {
            panelController?.hide(restoreFocus: true)
            showToast("Copied — press ⌘V to paste")
            return
        }
        if !AccessibilityPermission.isTrusted {
            AccessibilityPermission.requestPrompt()
            accessibilityTrusted = AccessibilityPermission.isTrusted
            panelController?.hide(restoreFocus: true)
            showAccessibilityAlert()
            return
        }
        accessibilityTrusted = true
        let target = previousApp
        panelController?.hide(restoreFocus: false)
        pasteController.autoPaste(to: target) { [weak self] sent in
            guard let self else { return }
            if !sent {
                self.showToast("Could not send ⌘V. The item is on your clipboard.")
            }
        }
    }

    private func showAccessibilityAlert() {
        let alert = NSAlert()
        alert.alertStyle = .informational
        alert.messageText = "Accessibility Permission Needed for Auto-Paste"
        alert.informativeText = "Enable Clipboard Manager in System Settings → Privacy & Security → Accessibility. Your item is already on the clipboard, so you can also paste it manually now."
        alert.addButton(withTitle: "Open System Settings")
        alert.addButton(withTitle: "Not Now")
        if alert.runModal() == .alertFirstButtonReturn {
            AccessibilityPermission.openSystemSettings()
        }
    }

    func pasteSelectedSnippet() {
        guard let snippet = selectedSnippet else { return }
        pasteSnippet(snippet)
    }

    func pasteSnippet(_ snippet: Snippet) {
        guard pasteController.write(text: snippet.body) else { return }
        monitor.noteOwnPasteboardWrite()
        finalizePaste()
    }

    func copySnippet(_ snippet: Snippet) {
        guard pasteController.write(text: snippet.body) else { return }
        monitor.noteOwnPasteboardWrite()
        showToast("Snippet copied")
    }

    @discardableResult
    func createSnippet(title: String, body: String, notify: Bool = true) -> Snippet? {
        let trimmedTitle = title.trimmed.isEmpty ? "Untitled Snippet" : title.trimmed
        let snippet = Snippet(title: trimmedTitle, body: body)
        do {
            try database.saveSnippet(snippet)
            reloadSnippets(preserveSelection: false)
            selectedSnippetID = snippet.id
            if notify { showToast("Snippet created") }
            return snippet
        } catch {
            showAlert(title: "Could Not Save Snippet", message: error.localizedDescription)
            return nil
        }
    }

    @discardableResult
    func updateSnippet(_ snippet: Snippet, title: String, body: String, notify: Bool = true) -> Snippet? {
        var updated = snippet
        updated.title = title.trimmed.isEmpty ? "Untitled Snippet" : title.trimmed
        updated.body = body
        updated.updatedAt = Date()
        do {
            try database.saveSnippet(updated)
            reloadSnippets(preserveSelection: true)
            selectedSnippetID = updated.id
            if notify { showToast("Snippet saved") }
            return updated
        } catch {
            showAlert(title: "Could Not Save Snippet", message: error.localizedDescription)
            return nil
        }
    }

    func deleteSnippet(_ snippet: Snippet) {
        do {
            try database.deleteSnippet(id: snippet.id)
            reloadSnippets(preserveSelection: false)
            showToast("Snippet deleted")
        } catch {
            showAlert(title: "Could Not Delete Snippet", message: error.localizedDescription)
        }
    }

    func saveSelectedAsSnippet() {
        guard let item = selectedItem, let text = item.plainText, !text.isEmpty else {
            showToast("Select a text item first")
            return
        }
        let title = item.titleText
        _ = createSnippet(title: title, body: text)
        mode = .snippets
    }

    func captureCurrentClipboard() {
        monitor.captureCurrentClipboard(force: true)
        showToast("Current clipboard captured")
    }

    func updateLaunchAtLogin(_ enabled: Bool) {
        if let error = settings.updateLaunchAtLogin(enabled) {
            showAlert(title: "Launch at Login Could Not Be Changed", message: error)
        }
        launchAtLoginStatus = LaunchAtLoginManager.statusText
    }

    func openSettings() {
        settingsWindowController?.show()
    }

    func exportBackup() {
        NSApp.activate(ignoringOtherApps: true)
        let panel = NSSavePanel()
        panel.title = "Export Clipboard Manager Backup"
        panel.allowedContentTypes = [.json]
        let formatter = DateFormatter()
        formatter.dateFormat = "yyyy-MM-dd"
        panel.nameFieldStringValue = "Clipboard Manager Backup \(formatter.string(from: Date())).json"
        guard panel.runModal() == .OK, let url = panel.url else { return }
        do {
            let data = try BackupManager.exportData(
                items: items,
                snippets: snippets,
                imageStore: imageStore
            )
            try data.write(to: url, options: .atomic)
            showToast("Backup exported")
        } catch {
            showAlert(title: "Export Failed", message: error.localizedDescription)
        }
    }

    func importBackup() {
        NSApp.activate(ignoringOtherApps: true)
        let panel = NSOpenPanel()
        panel.title = "Import Clipboard Manager Backup"
        panel.allowedContentTypes = [.json]
        panel.allowsMultipleSelection = false
        guard panel.runModal() == .OK, let url = panel.url else { return }
        do {
            let data = try Data(contentsOf: url)
            let result = try BackupManager.importData(
                data,
                database: database,
                imageStore: imageStore
            )
            reloadItems(preserveSelection: false)
            reloadSnippets(preserveSelection: true)
            showToast("Imported \(result.items) items and \(result.snippets) snippets")
        } catch {
            showAlert(title: "Import Failed", message: error.localizedDescription)
        }
    }

    func revealDataFolder() {
        NSWorkspace.shared.activateFileViewerSelecting([paths.applicationSupportDirectory])
    }

    func saveImage(_ item: ClipItem) {
        guard let fileName = item.imageFileName,
              let image = imageStore.image(named: fileName) else {
            showToast("Image file is no longer available")
            return
        }
        NSApp.activate(ignoringOtherApps: true)
        let panel = NSSavePanel()
        panel.title = "Save Clipboard Image"
        panel.allowedContentTypes = [.png]
        panel.nameFieldStringValue = "Clipboard Image \(Int(Date().timeIntervalSince1970)).png"
        guard panel.runModal() == .OK, let url = panel.url, let data = image.pngData else { return }
        do {
            try data.write(to: url, options: .atomic)
            showToast("Image saved")
        } catch {
            showAlert(title: "Could Not Save Image", message: error.localizedDescription)
        }
    }

    func showToast(_ message: String) {
        toastWorkItem?.cancel()
        toast = message
        let workItem = DispatchWorkItem { [weak self] in
            self?.toast = nil
        }
        toastWorkItem = workItem
        DispatchQueue.main.asyncAfter(deadline: .now() + 2.4, execute: workItem)
    }

    func showAlert(title: String, message: String) {
        let alert = NSAlert()
        alert.alertStyle = .warning
        alert.messageText = title
        alert.informativeText = message
        alert.addButton(withTitle: "OK")
        alert.runModal()
    }
}
