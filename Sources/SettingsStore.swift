import Foundation
import Combine

@MainActor
final class SettingsStore: ObservableObject {
    private enum Keys {
        static let maxItems = "maxItems"
        static let retentionDays = "retentionDays"
        static let ocrEnabled = "ocrEnabled"
        static let pasteAutomatically = "pasteAutomatically"
        static let pasteRichText = "pasteRichText"
        static let skipConcealed = "skipConcealed"
        static let skipAutoGenerated = "skipAutoGenerated"
        static let monitorEnabled = "monitorEnabled"
        static let shortcut = "shortcut"
        static let launchAtLogin = "launchAtLogin"
    }

    private let defaults: UserDefaults

    @Published var maxItems: Int {
        didSet {
            defaults.set(maxItems, forKey: Keys.maxItems)
            onHistorySettingsChanged?()
        }
    }

    @Published var retentionDays: Int {
        didSet {
            defaults.set(retentionDays, forKey: Keys.retentionDays)
            onHistorySettingsChanged?()
        }
    }

    @Published var ocrEnabled: Bool {
        didSet {
            defaults.set(ocrEnabled, forKey: Keys.ocrEnabled)
            onHistorySettingsChanged?()
        }
    }

    @Published var pasteAutomatically: Bool {
        didSet { defaults.set(pasteAutomatically, forKey: Keys.pasteAutomatically) }
    }

    @Published var pasteRichText: Bool {
        didSet { defaults.set(pasteRichText, forKey: Keys.pasteRichText) }
    }

    @Published var skipConcealed: Bool {
        didSet {
            defaults.set(skipConcealed, forKey: Keys.skipConcealed)
            onMonitorSettingsChanged?()
        }
    }

    @Published var skipAutoGenerated: Bool {
        didSet {
            defaults.set(skipAutoGenerated, forKey: Keys.skipAutoGenerated)
            onMonitorSettingsChanged?()
        }
    }

    @Published var monitorEnabled: Bool {
        didSet {
            defaults.set(monitorEnabled, forKey: Keys.monitorEnabled)
            onMonitorSettingsChanged?()
        }
    }

    @Published var shortcut: GlobalShortcut {
        didSet {
            if let data = try? JSONEncoder().encode(shortcut) {
                defaults.set(data, forKey: Keys.shortcut)
            }
            onShortcutChanged?(shortcut)
        }
    }

    @Published private(set) var launchAtLogin: Bool

    var onHistorySettingsChanged: (() -> Void)?
    var onMonitorSettingsChanged: (() -> Void)?
    var onShortcutChanged: ((GlobalShortcut) -> Void)?

    init(defaults: UserDefaults = .standard) {
        self.defaults = defaults
        maxItems = defaults.object(forKey: Keys.maxItems) as? Int ?? 500
        retentionDays = defaults.object(forKey: Keys.retentionDays) as? Int ?? 90
        ocrEnabled = defaults.object(forKey: Keys.ocrEnabled) as? Bool ?? true
        pasteAutomatically = defaults.object(forKey: Keys.pasteAutomatically) as? Bool ?? true
        pasteRichText = defaults.object(forKey: Keys.pasteRichText) as? Bool ?? true
        skipConcealed = defaults.object(forKey: Keys.skipConcealed) as? Bool ?? true
        skipAutoGenerated = defaults.object(forKey: Keys.skipAutoGenerated) as? Bool ?? true
        monitorEnabled = defaults.object(forKey: Keys.monitorEnabled) as? Bool ?? true
        if let data = defaults.data(forKey: Keys.shortcut),
           let decoded = try? JSONDecoder().decode(GlobalShortcut.self, from: data) {
            shortcut = decoded
        } else {
            shortcut = .defaultValue
        }
        launchAtLogin = LaunchAtLoginManager.isEnabled
    }

    func refreshLaunchAtLogin() {
        launchAtLogin = LaunchAtLoginManager.isEnabled
    }

    @discardableResult
    func updateLaunchAtLogin(_ enabled: Bool) -> String? {
        do {
            try LaunchAtLoginManager.setEnabled(enabled)
            launchAtLogin = LaunchAtLoginManager.isEnabled
            return nil
        } catch {
            launchAtLogin = LaunchAtLoginManager.isEnabled
            return error.localizedDescription
        }
    }

    func resetToDefaults() {
        maxItems = 500
        retentionDays = 90
        ocrEnabled = true
        pasteAutomatically = true
        pasteRichText = true
        skipConcealed = true
        skipAutoGenerated = true
        monitorEnabled = true
        shortcut = .defaultValue
    }
}
