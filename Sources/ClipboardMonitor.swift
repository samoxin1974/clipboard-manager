import Foundation
import AppKit

final class ClipboardMonitor {
    private let pasteboard: NSPasteboard
    private let normalizer: ClipboardNormalizer
    private var timer: Timer?
    private var lastChangeCount: Int
    private var ignoredChangeCount: Int?
    private var paused = false
    private var skipConcealed = true
    private var skipAutoGenerated = true

    var onCapture: ((ClipItem) -> Void)?

    init(pasteboard: NSPasteboard = .general, normalizer: ClipboardNormalizer) {
        self.pasteboard = pasteboard
        self.normalizer = normalizer
        self.lastChangeCount = pasteboard.changeCount
    }

    func start() {
        stop()
        lastChangeCount = pasteboard.changeCount
        let timer = Timer(timeInterval: 0.35, repeats: true) { [weak self] _ in
            self?.tick()
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
        AppLog.write("clipboard monitor started")
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    func setPaused(_ value: Bool) {
        paused = value
        if value {
            lastChangeCount = pasteboard.changeCount
        }
    }

    func configure(skipConcealed: Bool, skipAutoGenerated: Bool) {
        self.skipConcealed = skipConcealed
        self.skipAutoGenerated = skipAutoGenerated
    }

    func noteOwnPasteboardWrite() {
        ignoredChangeCount = pasteboard.changeCount
    }

    func captureCurrentClipboard(force: Bool = false) {
        if paused && !force { return }
        lastChangeCount = pasteboard.changeCount
        capture()
    }

    private func tick() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        if paused { return }
        if let ignored = ignoredChangeCount, ignored == count {
            ignoredChangeCount = nil
            return
        }
        capture()
    }

    private func capture() {
        let app = NSWorkspace.shared.frontmostApplication
        let sourceBundleID = app?.bundleIdentifier
        let sourceName = app?.localizedName
        guard let item = normalizer.makeItem(
            from: pasteboard,
            sourceBundleID: sourceBundleID,
            sourceName: sourceName,
            skipConcealed: skipConcealed,
            skipAutoGenerated: skipAutoGenerated
        ) else {
            AppLog.write("clipboard skipped: no supported content")
            return
        }
        onCapture?(item)
    }
}
