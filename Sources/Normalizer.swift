import Foundation
import AppKit

final class ClipboardNormalizer {
    let imageStore: ImageStore

    init(imageStore: ImageStore) {
        self.imageStore = imageStore
    }

    func makeItem(
        from pasteboard: NSPasteboard,
        sourceBundleID: String?,
        sourceName: String?,
        capturedAt: Date = Date(),
        skipConcealed: Bool = true,
        skipAutoGenerated: Bool = true
    ) -> ClipItem? {
        let types = Set(pasteboard.types ?? [])
        if skipConcealed, types.contains(.concealed) { return nil }
        if skipConcealed, types.contains(.transient) { return nil }
        if skipAutoGenerated, types.contains(.autoGenerated) { return nil }

        let ownBundleID = Bundle.main.bundleIdentifier
        let effectiveSourceID = sourceBundleID == ownBundleID ? nil : sourceBundleID
        let effectiveSourceName = sourceBundleID == ownBundleID ? nil : sourceName

        if let fileItem = fileItem(
            from: pasteboard,
            sourceBundleID: effectiveSourceID,
            sourceName: effectiveSourceName,
            capturedAt: capturedAt
        ) {
            return fileItem
        }

        if let imageItem = imageItem(
            from: pasteboard,
            sourceBundleID: effectiveSourceID,
            sourceName: effectiveSourceName,
            capturedAt: capturedAt
        ) {
            return imageItem
        }

        if let colorItem = colorItem(
            from: pasteboard,
            sourceBundleID: effectiveSourceID,
            sourceName: effectiveSourceName,
            capturedAt: capturedAt
        ) {
            return colorItem
        }

        return textItem(
            from: pasteboard,
            sourceBundleID: effectiveSourceID,
            sourceName: effectiveSourceName,
            capturedAt: capturedAt
        )
    }

    private func fileItem(
        from pasteboard: NSPasteboard,
        sourceBundleID: String?,
        sourceName: String?,
        capturedAt: Date
    ) -> ClipItem? {
        let options: [NSPasteboard.ReadingOptionKey: Any] = [.urlReadingFileURLsOnly: true]
        guard let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: options) as? [URL],
              !urls.isEmpty else { return nil }
        let paths = urls.filter { $0.isFileURL }.map(\.path)
        guard !paths.isEmpty else { return nil }
        let sorted = paths.sorted()
        let byteSize = paths.reduce(0) { partial, path in
            let attributes = try? FileManager.default.attributesOfItem(atPath: path)
            let size = (attributes?[.size] as? NSNumber)?.intValue ?? 0
            return partial + size
        }
        let hash = StableHash.string("file|" + sorted.joined(separator: "|"))
        let search = SearchTextBuilder.build(
            kind: .file,
            plainText: nil,
            htmlText: nil,
            filePaths: paths,
            colorHex: nil,
            sourceName: sourceName,
            ocrText: nil
        )
        return ClipItem(
            createdAt: capturedAt,
            kind: .file,
            filePaths: paths,
            sourceBundleID: sourceBundleID,
            sourceName: sourceName,
            contentHash: hash,
            byteSize: byteSize,
            searchText: search
        )
    }

    private func imageItem(
        from pasteboard: NSPasteboard,
        sourceBundleID: String?,
        sourceName: String?,
        capturedAt: Date
    ) -> ClipItem? {
        let imageTypes: [NSPasteboard.PasteboardType] = [.png, .tiff]
        guard let type = imageTypes.first(where: { pasteboard.data(forType: $0) != nil }),
              let data = pasteboard.data(forType: type) else { return nil }
        guard data.count <= 30 * 1024 * 1024 else {
            AppLog.write("clipboard image skipped: too large")
            return nil
        }
        let hash = StableHash.data(data)
        do {
            let stored = try imageStore.save(data: data, hash: hash)
            let search = SearchTextBuilder.build(
                kind: .image,
                plainText: nil,
                htmlText: nil,
                filePaths: [],
                colorHex: nil,
                sourceName: sourceName,
                ocrText: nil
            )
            return ClipItem(
                createdAt: capturedAt,
                kind: .image,
                imageFileName: stored.fileName,
                imageWidth: stored.width,
                imageHeight: stored.height,
                sourceBundleID: sourceBundleID,
                sourceName: sourceName,
                contentHash: hash,
                byteSize: data.count,
                searchText: search
            )
        } catch {
            AppLog.write("clipboard image save failed: \(error.localizedDescription)")
            return nil
        }
    }

    private func colorItem(
        from pasteboard: NSPasteboard,
        sourceBundleID: String?,
        sourceName: String?,
        capturedAt: Date
    ) -> ClipItem? {
        guard pasteboard.types?.contains(.color) == true else { return nil }
        let colors = pasteboard.readObjects(forClasses: [NSColor.self], options: nil) as? [NSColor]
        guard let color = colors?.first else { return nil }
        let hex = color.hexRGB
        let hash = StableHash.string("color|\(hex)")
        let search = SearchTextBuilder.build(
            kind: .color,
            plainText: hex,
            htmlText: nil,
            filePaths: [],
            colorHex: hex,
            sourceName: sourceName,
            ocrText: nil
        )
        return ClipItem(
            createdAt: capturedAt,
            kind: .color,
            plainText: hex,
            colorHex: hex,
            sourceBundleID: sourceBundleID,
            sourceName: sourceName,
            contentHash: hash,
            byteSize: hex.utf8.count,
            searchText: search
        )
    }

    private func textItem(
        from pasteboard: NSPasteboard,
        sourceBundleID: String?,
        sourceName: String?,
        capturedAt: Date
    ) -> ClipItem? {
        let explicitURL = pasteboard.string(forType: .URL)
        var plainText = pasteboard.string(forType: .string)
        var htmlText = pasteboard.string(forType: .html)
        let rtfData = pasteboard.data(forType: .rtf)

        if htmlText == nil, let rtfData {
            htmlText = HTMLTools.html(fromRTF: rtfData)
            if plainText == nil {
                plainText = HTMLTools.plainText(fromRTF: rtfData)
            }
        }
        if plainText == nil, let htmlText {
            plainText = HTMLTools.plainText(from: htmlText)
        }

        if let explicitURL, !explicitURL.trimmed.isEmpty {
            let normalized = URLTools.normalizedURLString(explicitURL)
            return makeTextItem(
                kind: .link,
                plainText: normalized,
                htmlText: htmlText,
                sourceBundleID: sourceBundleID,
                sourceName: sourceName,
                capturedAt: capturedAt
            )
        }

        guard let plainText, !plainText.isEmpty else { return nil }
        guard plainText.utf8.count <= 1_024 * 1_024 else {
            AppLog.write("clipboard text skipped: too large")
            return nil
        }
        if URLTools.isLikelyURL(plainText) {
            return makeTextItem(
                kind: .link,
                plainText: URLTools.normalizedURLString(plainText),
                htmlText: htmlText,
                sourceBundleID: sourceBundleID,
                sourceName: sourceName,
                capturedAt: capturedAt
            )
        }
        let kind: ClipKind = (htmlText?.isEmpty == false) ? .richText : .text
        return makeTextItem(
            kind: kind,
            plainText: plainText,
            htmlText: kind == .richText ? htmlText : nil,
            sourceBundleID: sourceBundleID,
            sourceName: sourceName,
            capturedAt: capturedAt
        )
    }

    private func makeTextItem(
        kind: ClipKind,
        plainText: String,
        htmlText: String?,
        sourceBundleID: String?,
        sourceName: String?,
        capturedAt: Date
    ) -> ClipItem {
        let hashSource = "\(kind.rawValue)|\(plainText)|\(htmlText ?? "")"
        let hash = StableHash.string(hashSource)
        let search = SearchTextBuilder.build(
            kind: kind,
            plainText: plainText,
            htmlText: htmlText,
            filePaths: [],
            colorHex: nil,
            sourceName: sourceName,
            ocrText: nil
        )
        return ClipItem(
            createdAt: capturedAt,
            kind: kind,
            plainText: plainText,
            htmlText: htmlText,
            sourceBundleID: sourceBundleID,
            sourceName: sourceName,
            contentHash: hash,
            byteSize: plainText.utf8.count + (htmlText?.utf8.count ?? 0),
            searchText: search
        )
    }
}
